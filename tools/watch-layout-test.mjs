// 23.11.8: the watch's layout check as a test (node --test tools/watch-layout-test.mjs):
//  1. every screen and state of tools/watch-scenes.mjs, drawn by js/watchscreens.js on a Dc that measures like each of the five watches
//     (the fenix 8 also at its font size setting 0.8 and 1.45), has no finding of tools/watch-layout.mjs (overlap, off the round screen,
//     under a bezel arc / pill / dot, cut, letters in a digits-only font, below 13 px);
//  2. garmin/source/Draw.mc (and Glance.mc's glance) and js/watchscreens.js have the same fractional numbers function by function, so
//     the JavaScript layout that is checked here is the one the watch draws.
// The real Garmin fonts are not in the repo (nor needed here): js/watchdc.js measures with their numbers, js/watchfontdata.js
// (generated by tools/watch-fonts-gen.py).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { RUNS, check, render } from './watch-layout.mjs';
import { SCENES } from './watch-scenes.mjs';

for (const [dev, k] of RUNS) {
  test(`layout: no findings on ${dev}${k !== 1 ? ' at font size ' + k : ''}`, () => {
    const out = [];
    for (const sc of SCENES) for (const f of check(render(sc, dev, k))) out.push(`${sc[0]}: ${f.kind}: ${f.msg}`);
    assert.deepEqual(out, []);
  });
}

/** source without comments and string literals */
function bare(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\]|\\.)*`/g, '""').replace(/\/\/[^\n]*/g, '');
}
/** function name -> its source (from its header to the next function header) */
function chunks(src, head) {
  const lines = bare(src).split('\n'), out = new Map(); let name = null, buf = [];
  const flush = () => { if (name) out.set(name, (out.get(name) || '') + buf.join('\n')); };
  for (const l of lines) { const m = l.match(head); if (m) { flush(); name = m[1] || m[2]; buf = [l]; } else if (name) buf.push(l); }
  flush(); return out;
}
/** the non-integer number literals of a source, sorted */
const fracs = s => (s.match(/(?<![\w.])(\d*\.\d+|\d+\.\d*)(?![\w.])/g) || []).map(Number).filter(n => !Number.isInteger(n)).sort((a, b) => a - b);

test('layout: Draw.mc and Glance.mc have the numbers of js/watchscreens.js, function by function', () => {
  const js = chunks(readFileSync(new URL('../js/watchscreens.js', import.meta.url), 'utf8'), /^(?:export\s+)?(?:function\s+(\w+)\s*\(|const\s+(\w+)\s*=)/);
  const mcHead = /^\s*function\s+(\w+)\s*\(/, mc = chunks(readFileSync(new URL('../garmin/source/Draw.mc', import.meta.url), 'utf8'), mcHead);
  mc.set('glance', chunks(readFileSync(new URL('../garmin/source/Glance.mc', import.meta.url), 'utf8'), mcHead).get('glance'));
  const diff = [], both = [...js.keys()].filter(n => mc.has(n));
  assert.ok(both.length >= 50, `only ${both.length} functions in both files`);
  // trStats: the normalized power's fourth root (.25) is Trainer.mc TRide.sum()'s on the watch
  const only = { trStats: [.25] };
  for (const n of both) { const a = fracs(js.get(n)).filter(x => !(only[n] || []).includes(x)).join(' '), b = fracs(mc.get(n)).join(' '); if (a !== b) diff.push(`${n}: js [${a}] mc [${b}]`); }
  assert.deepEqual(diff, []);
  // every screen of watchscreens.js is in Draw.mc (drawGlance: the preview's glance list, Glance.mc draws only its own row)
  const screens = [...js.keys()].filter(n => /^draw[A-Z]/.test(n) && n !== 'drawGlance');
  assert.deepEqual(screens.filter(n => !mc.has(n)), []);
});
