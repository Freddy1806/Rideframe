#!/usr/bin/env python3
# 23.11.8: generates js/watchfontdata.js, the numbers js/watchdc.js measures with (tools/watch-layout.mjs, the preview):
#   - per watch the system fonts' box height, ascent and descent and the measured widths, from the Connect IQ simulator's tables
#     (garmin_font_tables.json: dc.getFontHeight, Graphics.getFontAscent / Descent, dc.getTextWidthInPixels at font scale 1.0);
#   - per font family the glyph advances and ink, from the device fonts (RobotoCondensed-Bold, Roboto-Regular, Bionic semibold).
# The fonts and the tables are NOT in the repo and must never be (licence): only the numbers below are. Point GARMIN_FONTS at a
# folder with RobotoCondensed-Bold.ttf, Roboto-Regular.ttf, Bionic_semibold.ttf and garmin_font_tables.json.
# Usage: GARMIN_FONTS=/path/to/fonts python3 tools/watch-fonts-gen.py        (needs Pillow)
import json, os, sys
from PIL import ImageFont

G = os.environ.get('GARMIN_FONTS')
if not G: sys.exit('GARMIN_FONTS: the folder with the device fonts and garmin_font_tables.json (not in the repo)')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'watchfontdata.js')
FAMS = {'rcb': 'RobotoCondensed-Bold.ttf', 'bionic': 'Bionic_semibold.ttf', 'roboto': 'Roboto-Regular.ttf'}
CHARS = [chr(c) for c in range(32, 127)] + ['×', '−', '…', '·', '✓', '±']

# glyph advances and ink at 1000 px (1/1000 em)
M = {}
for k, f in FAMS.items():
    ft = ImageFont.truetype(os.path.join(G, f), 1000); adv = {}; ink = {}
    for ch in CHARS:
        try: a = ft.getlength(ch); bb = ft.getbbox(ch, anchor='ls')
        except Exception: a = None
        adv[ch] = round(a) if a is not None else None
        ink[ch] = [-bb[1], bb[3]] if a is not None else None  # ink above the baseline, below it
    M[k] = {'adv': adv, 'ink': ink}

T = json.load(open(os.path.join(G, 'garmin_font_tables.json')))
IDS = ['XTINY', 'TINY', 'SMALL', 'MEDIUM', 'LARGE', 'NUMBER_MILD', 'NUMBER_MEDIUM', 'NUMBER_HOT', 'NUMBER_THAI_HOT']
KEYS = ['xtiny', 'tiny', 'small', 'medium', 'large', 'numberMild', 'numberMedium', 'numberHot', 'numberThaiHot']
FAM = {'RobotoCondensed-Bold': 'rcb', 'Bionic_semibold': 'bionic', 'Roboto-Regular': 'roboto'}

def cal(k, x):
    """a bitmap font (fenix 7): the look-alike family at the px size that matches the measured widths"""
    num = k.startswith('number'); fm = M['bionic' if num else 'rcb']
    ss = [s for s in x['measured']['widths'] if (not num) or all(c in '0123456789.:' for c in s)]
    r = [x['measured']['widths'][s] / (sum(fm['adv'][c] for c in s) / 1000) for s in ss]
    return ('bionic' if num else 'rcb'), round(sum(r) / len(r), 1)

out = {}
for dev in ['fenix8solar47mm', 'fr265', 'fr265s', 'fenix7pro', 'fenix7xpro']:
    d = T[dev]; fs = {}
    for i, k in zip(IDS, KEYS):
        x = d['fonts'][k]; m = x['measured']
        f, px = (FAM[x['file']], x['px_em']) if x['type'] == 'ttf' else cal(k, x)
        fs[i] = [f, px, m['height'], m['ascent'], m['descent']]
    out[dev] = {'S': d['resolution']['width'], 'scale': [d['fontScaling']['fontScaleMin'], d['fontScaling']['fontScaleMax']] if d['fontScaling'] else None,
                'bitmap': d['fonts']['xtiny']['type'] != 'ttf', 'fonts': fs}
met = {}
for k, v in M.items():
    chars = ''.join(c for c in v['adv'] if v['adv'][c] is not None)
    met[k] = {'chars': chars, 'adv': [v['adv'][c] for c in chars], 'ink': [v['ink'][c] for c in chars]}
js = '// GENERATED by tools/watch-fonts-gen.py from the Connect IQ SDK 9.3 simulator tables (dc.getFontHeight, Graphics.getFontAscent / Descent,\n'
js += '// dc.getTextWidthInPixels at font scale 1.0, measured 23.11.2026) and the glyph advances / ink of the device fonts (RobotoCondensed-Bold,\n'
js += '// Roboto-Regular, Bionic semibold; the fenix 7 bitmap fonts approximated by them at the px size that matches the measured widths).\n'
js += '// The fonts themselves are not in the repo; only these numbers. Do not edit by hand.\n'
js += '/** per device: S (screen px), scale (the fenix 8 font size setting [min, max]; null = fixed), bitmap (fenix 7: bitmap fonts, the NUMBER\n *  fonts carry digits only), fonts[id] = [family, px, box height, ascent, descent] (box: dc.getFontHeight; VCENTER centres it) */\n'
js += 'export const DEV = ' + json.dumps(out, separators=(',', ':')) + ';\n'
js += '/** per family: chars, advance (1/1000 em) and ink [above, below the baseline] (1/1000 em) of each char, in the order of chars */\n'
js += 'export const MET = ' + json.dumps(met, separators=(',', ':')) + ';\n'
open(OUT, 'w').write(js)
print(OUT, len(js), 'bytes')
